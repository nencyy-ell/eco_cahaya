<<policy_setup>>
declare
  table_name text;
  policy_name text;
begin
  foreach table_name in array array[
    'bank_accounts', 'products_db', 'orders', 'prices', 'deposits', 'gold_batches', 'sembako_requests',
    'redemption_requests', 'bank_settings', 'waste_outflows'
  ] loop
    for policy_name in
      select p.policyname
      from pg_policies p
      where p.schemaname = 'public' and p.tablename = policy_setup.table_name
    loop
      execute format('drop policy %I on public.%I', policy_name, table_name);
    end loop;
  end loop;
end;
$$;

