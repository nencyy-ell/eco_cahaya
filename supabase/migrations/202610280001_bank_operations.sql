create or replace function public.validate_waste_outflow()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  available_weight numeric(12, 2);
begin
  perform pg_advisory_xact_lock(hashtext(new.waste_type));
  if tg_op = 'UPDATE' then
    select coalesce(sum(weight), 0) into available_weight
    from public.deposits
    where waste_type = new.waste_type;

    available_weight := available_weight - coalesce((
      select sum(weight) from public.waste_outflows
      where waste_type = new.waste_type and id <> old.id
    ), 0);
  else
    select coalesce(sum(weight), 0) into available_weight
    from public.deposits
    where waste_type = new.waste_type;

    available_weight := available_weight - coalesce((
      select sum(weight) from public.waste_outflows
      where waste_type = new.waste_type
    ), 0);
  end if;

  if new.weight > available_weight then
    raise exception 'Stok tersedia hanya % kg.', greatest(available_weight, 0);
  end if;
  return new;
end;
$$;

drop trigger if exists validate_waste_outflow_before_write on public.waste_outflows;
create trigger validate_waste_outflow_before_write
before insert or update on public.waste_outflows
for each row execute function public.validate_waste_outflow();

