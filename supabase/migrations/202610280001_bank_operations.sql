create table if not exists public.bank_accounts (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  full_name text not null,
  phone text not null default '',
  role text not null default 'resident' check (role in ('resident', 'admin')),
  status text not null default 'pending' check (status in ('pending', 'active', 'rejected')),
  created_at timestamptz not null default now()
);

alter table public.bank_accounts enable row level security;
create unique index if not exists bank_accounts_active_resident_name
  on public.bank_accounts (lower(trim(full_name)))
  where role = 'resident' and status = 'active';

create or replace function public.is_bank_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.bank_accounts
    where user_id = auth.uid() and role = 'admin' and status = 'active'
  );
$$;

create or replace function public.create_bank_account()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.bank_accounts (user_id, email, full_name, phone)
  values (
    new.id,
    lower(new.email),
    trim(coalesce(new.raw_user_meta_data ->> 'full_name', '')),
    trim(coalesce(new.raw_user_meta_data ->> 'phone', ''))
  );
  return new;
end;
$$;

drop trigger if exists create_bank_account_after_signup on auth.users;
create trigger create_bank_account_after_signup
after insert on auth.users
for each row execute function public.create_bank_account();

