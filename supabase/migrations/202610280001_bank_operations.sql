do $$
declare
  product_id_type text;
begin
  select format_type(a.atttypid, a.atttypmod) into product_id_type
  from pg_attribute a
  join pg_class t on t.oid = a.attrelid
  join pg_namespace n on n.oid = t.relnamespace
  where n.nspname = 'public'
    and t.relname = 'products_db'
    and a.attname = 'id'
    and not a.attisdropped;

  if product_id_type is null then
    raise exception 'Kolom public.products_db.id tidak ditemukan.';
  end if;

  execute format(
    'alter table public.orders add column if not exists product_id %s',
    product_id_type
  );
end;
$$;

