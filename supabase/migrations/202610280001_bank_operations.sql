create or replace function public.reserve_order_inventory()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  current_price numeric(12, 2);
  current_title text;
begin
  if tg_op = 'INSERT' then
    if new.product_id is null or new.quantity <= 0 then
      raise exception 'Pilih produk dan jumlah pesanan yang valid.';
    end if;

    update public.products_db
    set stock = stock - new.quantity
    where id = new.product_id and stock >= new.quantity
    returning title, price_amount into current_title, current_price;

    if not found then
      raise exception 'Stok produk tidak cukup atau produk tidak ditemukan.';
    end if;
    if current_price <= 0 then
      raise exception 'Pengurus belum mengatur harga jual produk ini.';
    end if;

    new.product_name := current_title;
    new.total_amount := current_price * new.quantity;
    new.inventory_reserved := true;
    new.status := 'Baru';
    new.completed_at := null;
    return new;
  end if;

  if tg_op = 'UPDATE' and old.status = 'Selesai' and new.status = 'Ditolak' then
    raise exception 'Pesanan yang sudah selesai tidak dapat ditolak.';
  end if;

  if new.status = 'Selesai' then
    new.completed_at := coalesce(new.completed_at, now());
  elsif tg_op = 'UPDATE' then
    new.completed_at := null;
  end if;

  if tg_op = 'UPDATE' and old.inventory_reserved and new.status = 'Ditolak' then
    update public.products_db
    set stock = stock + old.quantity
    where id = old.product_id;
    new.inventory_reserved := false;
  end if;

  return new;
end;
$$;

drop trigger if exists reserve_order_inventory_before_write on public.orders;
create trigger reserve_order_inventory_before_write
before insert or update of status on public.orders
for each row execute function public.reserve_order_inventory();

