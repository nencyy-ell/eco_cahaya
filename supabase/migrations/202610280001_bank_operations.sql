create or replace function public.request_balance_redemption(
  p_redemption_type text,
  p_amount numeric,
  p_item_details text,
  p_quantity numeric default 1
)
returns public.redemption_requests
language plpgsql
security definer
set search_path = public
as $$
declare
  account public.bank_accounts%rowtype;
  available_balance numeric(12, 2);
  settings public.bank_settings%rowtype;
  new_request public.redemption_requests%rowtype;
begin
  select * into account
  from public.bank_accounts
  where user_id = auth.uid() and role = 'resident' and status = 'active'
  for update;

  if not found then
    raise exception 'Akun warga belum aktif.';
  end if;
  if p_redemption_type not in ('gold', 'sembako') or p_amount <= 0 or p_quantity <= 0 then
    raise exception 'Data penukaran tidak valid.';
  end if;

  select * into settings from public.bank_settings where id = 1;
  if p_redemption_type = 'gold'
     and (p_amount < settings.gold_minimum or mod(p_amount, settings.gold_increment) <> 0) then
    raise exception 'Penukaran emas minimal Rp %, dengan kelipatan Rp %.',
      settings.gold_minimum, settings.gold_increment;
  end if;

  select coalesce(sum(nominal::numeric), 0) into available_balance
  from public.deposits
  where lower(trim(user_name)) = lower(trim(account.full_name));

  available_balance := available_balance - coalesce((
    select sum(amount) from public.redemption_requests
    where lower(trim(user_name)) = lower(trim(account.full_name))
      and status <> 'Ditolak'
  ), 0);

  if p_amount > available_balance then
    raise exception 'Saldo tersedia hanya Rp %.', greatest(available_balance, 0);
  end if;

  insert into public.redemption_requests
    (user_id, user_name, phone, redemption_type, amount, item_details, quantity)
  values
    (account.user_id, account.full_name, account.phone, p_redemption_type,
     p_amount, trim(coalesce(p_item_details, '')), p_quantity)
  returning * into new_request;

  return new_request;
end;
$$;

create or replace function public.get_resident_available_balance()
returns numeric
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  account public.bank_accounts%rowtype;
  deposited numeric(12, 2);
  redeemed numeric(12, 2);
begin
  select * into account
  from public.bank_accounts
  where user_id = auth.uid() and role = 'resident' and status = 'active';
  if not found then
    raise exception 'Akun warga belum aktif.';
  end if;

  select coalesce(sum(nominal::numeric), 0) into deposited
  from public.deposits
  where lower(trim(user_name)) = lower(trim(account.full_name));

  select coalesce(sum(amount), 0) into redeemed
  from public.redemption_requests
  where lower(trim(user_name)) = lower(trim(account.full_name))
    and status <> 'Ditolak';

  return greatest(deposited - redeemed, 0);
end;
$$;

