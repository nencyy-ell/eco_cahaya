create table if not exists public.activity_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users(id) on delete set null,
  actor_name text not null,
  actor_role text not null,
  entity_type text not null,
  entity_id text not null,
  action text not null,
  summary text not null,
  amount numeric(12, 2) not null default 0,
  created_at timestamptz not null default now()
);

alter table public.activity_logs enable row level security;

create policy activity_logs_admin_read on public.activity_logs
for select to authenticated using (public.is_bank_admin());

grant select on public.activity_logs to authenticated;

drop policy if exists orders_admin_manage on public.orders;
create policy orders_admin_select on public.orders
for select to authenticated using (public.is_bank_admin());
create policy orders_admin_insert on public.orders
for insert to authenticated with check (public.is_bank_admin());
create policy orders_admin_update on public.orders
for update to authenticated using (public.is_bank_admin()) with check (public.is_bank_admin());
revoke delete on public.orders from authenticated;

create or replace function public.record_transaction_activity()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  new_row jsonb := case when tg_op = 'DELETE' then '{}'::jsonb else to_jsonb(new) end;
  old_row jsonb := case when tg_op = 'INSERT' then '{}'::jsonb else to_jsonb(old) end;
  actor public.bank_accounts%rowtype;
  activity_action text;
  activity_summary text;
  activity_actor_name text;
  activity_actor_role text;
  activity_amount numeric(12, 2) := 0;
  record_id text;
begin
  select * into actor
  from public.bank_accounts
  where user_id = auth.uid();

  activity_actor_name := coalesce(actor.full_name, 'Pengguna');
  activity_actor_role := case
    when actor.role = 'admin' then 'Pengurus'
    when actor.role = 'resident' then 'Warga'
    else 'Pengunjung'
  end;
  record_id := coalesce(new_row ->> 'id', new_row ->> 'user_id', old_row ->> 'id', old_row ->> 'user_id', '');
  activity_amount := coalesce(
    nullif(new_row ->> 'total_amount', '')::numeric,
    nullif(new_row ->> 'amount', '')::numeric,
    nullif(new_row ->> 'nominal', '')::numeric,
    0
  );

  if tg_table_name = 'orders' then
    if tg_op = 'INSERT' then
      activity_action := 'pesanan_dibuat';
      activity_actor_name := coalesce(actor.full_name, new_row ->> 'buyer_name', activity_actor_name);
      if actor.user_id is null then activity_actor_role := 'Warga/Pembeli'; end if;
      activity_summary := format(
        'Pesanan #%s dibuat oleh %s: %s (%s pcs).',
        record_id, coalesce(new_row ->> 'buyer_name', 'pembeli'),
        coalesce(new_row ->> 'product_name', 'produk'), coalesce(new_row ->> 'quantity', '1')
      );
    elsif old_row ->> 'status' is distinct from new_row ->> 'status' then
      activity_action := 'status_pesanan_diubah';
      activity_summary := format(
        'Status pesanan #%s (%s) berubah dari %s menjadi %s.',
        record_id, coalesce(new_row ->> 'product_name', 'produk'),
        coalesce(old_row ->> 'status', 'tidak diketahui'),
        coalesce(new_row ->> 'status', 'tidak diketahui')
      );
    else
      return new;
    end if;
  elsif tg_table_name = 'deposits' and tg_op = 'INSERT' then
    activity_action := 'setoran_dicatat';
    activity_summary := format(
      'Setoran %s milik %s dicatat: %s kg senilai Rp %s.',
      coalesce(new_row ->> 'waste_type', 'sampah'),
      coalesce(new_row ->> 'user_name', 'warga'),
      coalesce(new_row ->> 'weight', '0'),
      coalesce(new_row ->> 'nominal', '0')
    );
  elsif tg_table_name = 'redemption_requests' then
    if tg_op = 'INSERT' then
      activity_action := 'penukaran_diajukan';
      activity_summary := format(
        'Pengajuan penukaran %s dari %s sebesar Rp %s dibuat.',
        coalesce(new_row ->> 'redemption_type', 'saldo'),
        coalesce(new_row ->> 'user_name', 'warga'),
        coalesce(new_row ->> 'amount', '0')
      );
    elsif old_row ->> 'status' is distinct from new_row ->> 'status' then
      activity_action := 'status_penukaran_diubah';
      activity_summary := format(
        'Status pengajuan penukaran #%s milik %s berubah dari %s menjadi %s.',
        record_id, coalesce(new_row ->> 'user_name', 'warga'),
        coalesce(old_row ->> 'status', 'tidak diketahui'),
        coalesce(new_row ->> 'status', 'tidak diketahui')
      );
    else
      return new;
    end if;
  elsif tg_table_name = 'bank_accounts' then
    if tg_op = 'INSERT' then
      activity_action := 'akun_warga_dibuat';
      activity_actor_name := coalesce(new_row ->> 'full_name', activity_actor_name);
      if actor.user_id is null then activity_actor_role := 'Warga'; end if;
      activity_summary := format('Akun warga %s dibuat dengan status %s.', coalesce(new_row ->> 'full_name', 'warga'), coalesce(new_row ->> 'status', 'tidak diketahui'));
    else
      if old_row ->> 'full_name' is not distinct from new_row ->> 'full_name'
        and old_row ->> 'phone' is not distinct from new_row ->> 'phone'
        and old_row ->> 'status' is not distinct from new_row ->> 'status' then
        return new;
      end if;
      activity_action := 'akun_warga_diubah';
      activity_summary := format(
        'Data akun warga %s diperbarui (status: %s).',
        coalesce(new_row ->> 'full_name', 'warga'), coalesce(new_row ->> 'status', 'tidak diketahui')
      );
    end if;
  elsif tg_table_name = 'waste_outflows' and tg_op = 'INSERT' then
    activity_action := 'stok_sampah_keluar_dicatat';
    activity_summary := format(
      'Pengeluaran %s kg %s dicatat pada %s.',
      coalesce(new_row ->> 'weight', '0'), coalesce(new_row ->> 'waste_type', 'sampah'),
      coalesce(new_row ->> 'movement_date', 'tanggal tidak diketahui')
    );
  else
    return new;
  end if;

  insert into public.activity_logs
    (actor_id, actor_name, actor_role, entity_type, entity_id, action, summary, amount)
  values
    (auth.uid(), activity_actor_name, activity_actor_role, tg_table_name, record_id, activity_action, activity_summary, activity_amount);
  return new;
end;
$$;

drop trigger if exists record_order_activity on public.orders;
create trigger record_order_activity
after insert or update on public.orders
for each row execute function public.record_transaction_activity();

